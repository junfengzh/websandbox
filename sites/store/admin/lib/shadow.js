'use strict';
// Per-tenant temp helpers of the back office, created in the tenant's onOpen (before the
// rollout BEGIN, so they are committed and survive resets).
//
// 1. temp.admin_pgrid -- a narrow shadow of `products` for the product grid. products rows are
//    wide (description HTML inline; qty, created_at, ... come after it), so filtering or sorting
//    on an unindexed column reads ~400 MB of pages (0.5-1 s). The shadow holds the short grid
//    columns (~8 MB per tenant); TEMP triggers on products keep it in sync, so writes inside the
//    rollout transaction update it and ROLLBACK reverts it together with products.
// 2. temp.admin_popt / temp.admin_povr -- base.db has no index on product_options(product_id)
//    or product_option_values(option_id); option values are contiguous id ranges per option, so
//    these small maps make the product page's custom options O(log n). Left empty when base.db
//    has the indexes.
// 4. temp.admin_report_runs / admin_report_rows -- report runs generated by the 'admin.report'
//    background job (empty at open; written inside the rollout transaction, so a reset clears them).
// 5. temp.newsletter_templates / temp.newsletter_queue -- Marketing > Communications (base.db has
//    no newsletter template / queue tables; tasks create them, so they start empty per rollout).
// 3. temp.admin_rstat -- ids of reviews that are NOT approved (a handful of 309k), so the
//    review grid's status filter (Pending Reviews) needs no scan of the reviews table.
//
// The rows come from a small SQLite file built once per base.db version (in /dev/shm, keyed by
// base.db's size/mtime/inode): reading products costs seconds, copying the prepared rows into a
// tenant's temp tables ~0.1-0.2 s. ATTACH is allowed here because onOpen runs before the kit's
// commit guard is installed.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');

const COLS = ['id', 'type', 'attribute_set_id', 'status', 'visibility', 'price', 'special_price', 'cost', 'weight', 'qty', 'is_in_stock', 'color', 'size', 'country_of_manufacture', 'created_at', 'updated_at', 'manage_stock', 'notify_stock_qty'];
const PGRID_DDL = `(id INTEGER PRIMARY KEY, type TEXT, attribute_set_id INTEGER, status INTEGER, visibility INTEGER,
  price REAL, special_price REAL, cost REAL, weight REAL, qty REAL, is_in_stock INTEGER, color TEXT, size TEXT, country_of_manufacture TEXT, created_at TEXT, updated_at TEXT, manage_stock INTEGER, notify_stock_qty REAL)`;
const list = COLS.join(', ');
const nw = COLS.map((c) => `new.${c}`).join(', ');
const VERSION = 3; // bump when the shadow file layout changes

const basePath = (db) => decodeURI(String(db.name).replace(/^file:/, '').replace(/\?.*$/, ''));
const hasIndex = (db, t, c) => !!db.prepare("SELECT 1 FROM main.sqlite_master WHERE type = 'index' AND tbl_name = ? AND sql LIKE ?").get(t, `%(${c}%`);

function shadowFile(db) {
  const base = basePath(db);
  const st = fs.statSync(base);
  const key = crypto.createHash('sha1').update(`${VERSION}|${path.resolve(base)}|${st.size}|${st.mtimeMs}|${st.ino}`).digest('hex').slice(0, 16);
  const dir = fs.existsSync('/dev/shm') ? '/dev/shm' : os.tmpdir();
  return { base, file: path.join(dir, `wsb-store-admin-${key}.db`) };
}

function buildShadowFile(db, base, file, opts) {
  const Database = db.constructor;
  const tmp = `${file}.${process.pid}.tmp`;
  fs.rmSync(tmp, { force: true });
  const s = new Database(tmp);
  try {
    s.pragma('journal_mode = OFF'); s.pragma('synchronous = OFF');
    s.prepare('ATTACH DATABASE ? AS b').run(`file:${encodeURI(base)}?mode=ro&nolock=1`);
    s.exec(`CREATE TABLE pgrid ${PGRID_DDL}; INSERT INTO pgrid (${list}) SELECT ${list} FROM b.products ORDER BY id;
      CREATE TABLE popt (product_id INTEGER, option_id INTEGER); CREATE TABLE povr (option_id INTEGER PRIMARY KEY, lo INTEGER, hi INTEGER);`);
    if (opts.popt) s.exec('INSERT INTO popt SELECT product_id, id FROM b.product_options ORDER BY product_id, id');
    s.exec("CREATE TABLE rstat (id INTEGER PRIMARY KEY, status TEXT); INSERT INTO rstat SELECT id, status FROM b.reviews WHERE status <> 'approved'");
    if (opts.povr) s.exec('INSERT INTO povr SELECT option_id, min(id), max(id) FROM b.product_option_values GROUP BY option_id');
    s.exec('DETACH DATABASE b');
  } finally { s.close(); }
  fs.renameSync(tmp, file);
}

function onOpen(db) {
  const needPopt = !hasIndex(db, 'product_options', 'product_id');
  const needPovr = !hasIndex(db, 'product_option_values', 'option_id');
  const { base, file } = shadowFile(db);
  if (!fs.existsSync(file)) buildShadowFile(db, base, file, { popt: needPopt, povr: needPovr });
  db.exec(`
    CREATE TEMP TABLE IF NOT EXISTS admin_pgrid ${PGRID_DDL};
    CREATE TEMP TABLE IF NOT EXISTS admin_popt (product_id INTEGER, option_id INTEGER);
    CREATE INDEX IF NOT EXISTS temp.admin_popt_p ON admin_popt(product_id);
    CREATE TEMP TABLE IF NOT EXISTS admin_povr (option_id INTEGER PRIMARY KEY, lo INTEGER, hi INTEGER);
    CREATE TEMP TABLE IF NOT EXISTS admin_rstat (id INTEGER PRIMARY KEY, status TEXT);
    DELETE FROM temp.admin_pgrid; DELETE FROM temp.admin_popt; DELETE FROM temp.admin_povr; DELETE FROM temp.admin_rstat;
    CREATE TEMP TABLE IF NOT EXISTS admin_report_runs (id INTEGER PRIMARY KEY, type TEXT NOT NULL, params TEXT, sig TEXT, status TEXT NOT NULL,
      created_at TEXT, finished_at TEXT, job_id INTEGER, row_count INTEGER, columns TEXT, totals TEXT, error TEXT);
    CREATE TEMP TABLE IF NOT EXISTS newsletter_templates (id INTEGER PRIMARY KEY, code TEXT NOT NULL, subject TEXT, sender_name TEXT, sender_email TEXT, text TEXT, styles TEXT,
      is_active INTEGER DEFAULT 1, added_at TEXT, modified_at TEXT);
    CREATE TEMP TABLE IF NOT EXISTS newsletter_queue (id INTEGER PRIMARY KEY, template_id INTEGER, subject TEXT, sender_name TEXT, sender_email TEXT, text TEXT,
      status INTEGER, start_at TEXT, finish_at TEXT, recipients INTEGER, sent INTEGER, job_id INTEGER);
    CREATE TEMP TABLE IF NOT EXISTS admin_report_rows (run_id INTEGER NOT NULL, n INTEGER NOT NULL, period TEXT, data TEXT, PRIMARY KEY (run_id, n));`);
  db.prepare('ATTACH DATABASE ? AS wsb_admin_shadow').run(file);
  try {
    db.exec(`INSERT INTO temp.admin_pgrid SELECT * FROM wsb_admin_shadow.pgrid;
      INSERT INTO temp.admin_popt SELECT * FROM wsb_admin_shadow.popt;
      INSERT INTO temp.admin_povr SELECT * FROM wsb_admin_shadow.povr;
      INSERT INTO temp.admin_rstat SELECT * FROM wsb_admin_shadow.rstat;`);
  } finally { db.exec('DETACH DATABASE wsb_admin_shadow'); }
  db.exec(`
    CREATE TEMP TRIGGER IF NOT EXISTS admin_pgrid_ai AFTER INSERT ON products BEGIN
      INSERT OR REPLACE INTO temp.admin_pgrid (${list}) VALUES (${nw}); END;
    CREATE TEMP TRIGGER IF NOT EXISTS admin_pgrid_au AFTER UPDATE ON products BEGIN
      DELETE FROM temp.admin_pgrid WHERE id = old.id;
      INSERT OR REPLACE INTO temp.admin_pgrid (${list}) VALUES (${nw}); END;
    CREATE TEMP TRIGGER IF NOT EXISTS admin_pgrid_ad AFTER DELETE ON products BEGIN
      DELETE FROM temp.admin_pgrid WHERE id = old.id; END;
    CREATE TEMP TRIGGER IF NOT EXISTS admin_rstat_ai AFTER INSERT ON reviews WHEN new.status <> 'approved' BEGIN
      INSERT OR REPLACE INTO temp.admin_rstat (id, status) VALUES (new.id, new.status); END;
    CREATE TEMP TRIGGER IF NOT EXISTS admin_rstat_au AFTER UPDATE OF status, id ON reviews BEGIN
      DELETE FROM temp.admin_rstat WHERE id = old.id;
      INSERT INTO temp.admin_rstat (id, status) SELECT new.id, new.status WHERE new.status <> 'approved'; END;
    CREATE TEMP TRIGGER IF NOT EXISTS admin_rstat_ad AFTER DELETE ON reviews BEGIN
      DELETE FROM temp.admin_rstat WHERE id = old.id; END;
    CREATE TEMP TRIGGER IF NOT EXISTS admin_popt_ai AFTER INSERT ON product_options BEGIN
      INSERT INTO temp.admin_popt (product_id, option_id) SELECT new.product_id, new.id WHERE EXISTS (SELECT 1 FROM temp.admin_popt LIMIT 1); END;
    CREATE TEMP TRIGGER IF NOT EXISTS admin_popt_ad AFTER DELETE ON product_options BEGIN
      DELETE FROM temp.admin_popt WHERE option_id = old.id; END;
  `);
}

// custom options of a product (+ values): base indexes when present, else the temp maps
function productOptions(db, pid) {
  const viaMap = !!db.prepare('SELECT 1 FROM temp.admin_popt LIMIT 1').get();
  const opts = viaMap
    ? db.prepare('SELECT o.* FROM temp.admin_popt m JOIN product_options o ON o.id = m.option_id WHERE m.product_id = ? ORDER BY o.position, o.id').all(pid)
    : db.prepare('SELECT * FROM product_options WHERE product_id = ? ORDER BY position, id').all(pid);
  const rangeMap = !!db.prepare('SELECT 1 FROM temp.admin_povr LIMIT 1').get();
  for (const o of opts) {
    const r = rangeMap ? db.prepare('SELECT lo, hi FROM temp.admin_povr WHERE option_id = ?').get(o.id) : null;
    o.values = rangeMap
      ? (r ? db.prepare('SELECT * FROM product_option_values WHERE id BETWEEN ? AND ? AND option_id = ? ORDER BY position, id').all(r.lo, r.hi, o.id) : [])
      : db.prepare('SELECT * FROM product_option_values WHERE option_id = ? ORDER BY position, id').all(o.id);
  }
  return opts;
}

module.exports = { onOpen, COLS, productOptions };
