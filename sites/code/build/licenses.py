#!/usr/bin/env python3
"""List every project with its upstream and the licence found in its default-branch tree.

Usage: python3 -I licenses.py --db base.db --out ../SOURCES.repos.md
Reads LICENSE*/LICENCE*/COPYING* at the repository root (git_objects) and classifies it by
well-known phrases. 'none found' means no licence file at the root of the default branch.
"""
import argparse, re, sqlite3, zlib

PATTERNS = [
    ('AGPL-3.0', r'GNU AFFERO GENERAL PUBLIC LICENSE'),
    ('LGPL-3.0', r'GNU LESSER GENERAL PUBLIC LICENSE\s+Version 3'),
    ('LGPL-2.1', r'GNU LESSER GENERAL PUBLIC LICENSE\s+Version 2\.1|GNU Library General Public'),
    ('GPL-3.0', r'GNU GENERAL PUBLIC LICENSE\s+Version 3'),
    ('GPL-2.0', r'GNU GENERAL PUBLIC LICENSE\s+Version 2'),
    ('Apache-2.0', r'Apache License,?\s+Version 2\.0'),
    ('MPL-2.0', r'Mozilla Public License,?\s+(version|v\.?)\s*2\.0'),
    ('EPL', r'Eclipse Public License'),
    ('BSD-3-Clause', r'Neither the name of .* nor the names of'),
    ('BSD-2-Clause', r'Redistributions in binary form must reproduce'),
    ('MIT', r'Permission is hereby granted, free of charge'),
    ('ISC', r'Permission to use, copy, modify, and/or distribute this software for any'),
    ('Unlicense', r'This is free and unencumbered software released into the public domain'),
    ('CC0-1.0', r'CC0 1\.0|Creative Commons Zero|CC0 Public Domain'),
    ('CC-BY-SA-4.0', r'Attribution-ShareAlike 4\.0'),
    ('CC-BY-4.0', r'Attribution 4\.0 International'),
    ('CC-BY-NC-SA-4.0', r'Attribution-NonCommercial-ShareAlike 4\.0'),
    ('WTFPL', r'DO WHAT THE FUCK YOU WANT'),
    ('Zlib', r'This software is provided .as-is., without any express or implied'),
    ('Artistic-2.0', r'Artistic License 2\.0'),
    ('BSL-1.0', r'Boost Software License'),
]


def body(db, sha):
    r = db.execute('SELECT enc, omitted, data FROM git_objects WHERE sha = ?', (sha,)).fetchone()
    if not r or r[1]:
        return None
    return zlib.decompress(r[2]) if r[0] == 1 else r[2]


def entries(data):
    i = 0
    while i < len(data):
        sp = data.index(b' ', i); nul = data.index(b'\0', sp)
        yield data[i:sp].decode(), data[sp + 1:nul].decode('utf-8', 'replace'), data[nul + 1:nul + 21].hex()
        i = nul + 21


def classify(text):
    for name, pat in PATTERNS:
        if re.search(pat, text, re.I | re.S):
            return name
    return 'other (see file)'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--db', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    db = sqlite3.connect(a.db)
    rows = []
    for pid, path, url, br, fork in db.execute('''SELECT p.id, p.full_path, p.import_url, p.default_branch, f.full_path
            FROM projects p LEFT JOIN projects f ON f.id = p.forked_from_id ORDER BY lower(p.full_path)'''):
        lic, fname = 'none found', ''
        r = db.execute('''SELECT c.tree_sha FROM refs r JOIN commits c ON c.sha = r.sha
                          WHERE r.project_id = ? AND r.kind = 'branch' AND r.name = ?''', (pid, br)).fetchone()
        if r:
            t = body(db, r[0])
            if t:
                for mode, name, sha in entries(t):
                    if re.match(r'(LICEN[CS]E|COPYING|UNLICENSE)', name, re.I) and mode != '40000':
                        b = body(db, sha)
                        if b:
                            lic, fname = classify(b.decode('utf-8', 'replace')), name
                            break
        up = url or (f'fork of {fork}' if fork else 'no import URL (pushed directly)')
        rows.append(f'| {path} | {up} | {lic} | {fname} |')
    with open(a.out, 'w') as f:
        f.write('# Repositories in the code-hosting data\n\nGenerated by `build/licenses.py` from base.db: each project, '
                'its upstream (GitLab import URL, credentials stripped), and the licence file found at the root of '
                'its default branch (classified by phrase matching; check the file for exact terms).\n\n'
                '| project | upstream | licence | file |\n|---|---|---|---|\n' + '\n'.join(rows) + '\n')
    print(f'{len(rows)} projects -> {a.out}')


if __name__ == '__main__':
    main()
